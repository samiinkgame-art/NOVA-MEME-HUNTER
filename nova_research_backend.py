def main():
    if sys.version_info < (3, 11):
        raise SystemExit("Python 3.11+ required")
    if len(sys.argv) > 1 and sys.argv[1] == "generate-key":
        print(secrets.token_urlsafe(48))
        return
    payload=base64.b64decode(PAYLOAD,validate=True)
    if hashlib.sha256(payload).hexdigest()!=PAYLOAD_SHA256:
        raise SystemExit("Embedded source integrity check failed")
    with tempfile.TemporaryDirectory(prefix="nova-research-") as directory:
        root=Path(directory)
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            for item in archive.infolist():
                path=PurePosixPath(item.filename)
                if path.is_absolute() or ".." in path.parts or path.parts[0] not in ("nova","tests"):
                    raise SystemExit("Invalid embedded source path")
                dest=root.joinpath(*path.parts)
                dest.parent.mkdir(parents=True,exist_ok=True)
                dest.write_bytes(archive.read(item))
        sys.path.insert(0,directory)
        os.environ["PYTHONPATH"]=directory+os.pathsep+os.environ.get("PYTHONPATH","")
        if len(sys.argv)>1 and sys.argv[1]=="self-test":
            suite=unittest.defaultTestLoader.discover(str(root/"tests"))
            result=unittest.TextTestRunner(verbosity=2).run(suite)
            raise SystemExit(0 if result.wasSuccessful() else 1)
        if len(sys.argv)>1 and sys.argv[1] not in ("serve",):
            from nova.__main__ import main as cli
            cli()
            return
        from nova.config import Config,load_env
        from nova.store import Store
        from nova.engine import Engine
        from nova.providers import DexScreener
        from nova.remote_server import serve,settings
        load_env()
        settings()  # Validate deployment configuration before touching the ledger.
        os.environ.setdefault("NOVA_DB","data/nova-research-0.1.1.db")
        os.environ.setdefault("NOVA_WATCHLIST","So11111111111111111111111111111111111111112")
        os.environ["NOVA_PORT"]=os.getenv("PORT",os.getenv("NOVA_PORT","8000"))
        cfg=Config.from_env()
        store=Store(cfg.db)
        serve(Engine(cfg,store,DexScreener()))


if __name__=="__main__":
    main()
